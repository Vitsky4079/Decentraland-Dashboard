-- ---------- Tables ----------

-- Single-row checkpoint for the incremental Catalyst sync.
create table if not exists public.map_sync_state (
  id                  integer primary key default 1 check (id = 1),
  last_successful_sync timestamptz,
  last_entity_id       text,
  created_at           timestamptz not null default now(),
  updated_at           timestamptz not null default now()
);
insert into public.map_sync_state (id) values (1) on conflict (id) do nothing;

-- One row per Catalyst scene deployment (a scene can span multiple parcels —
-- do not confuse this with scene_deployment_parcels below).
create table if not exists public.scene_deployments (
  id                  bigint generated by default as identity primary key,
  entity_id           text not null unique,
  previous_entity_id  text,
  deployed_at         timestamptz,        -- Catalyst entityTimestamp
  detected_at         timestamptz not null default now(),  -- when our sync saw it
  base_parcel_x       integer,
  base_parcel_y       integer,
  scene_name          text,
  metadata            jsonb,
  pointer_data        jsonb,              -- raw pointers array from Catalyst
  parcel_count        integer not null default 0,
  created_at          timestamptz not null default now()
);
create index if not exists scene_deployments_deployed_at_idx on public.scene_deployments (deployed_at desc);
create index if not exists scene_deployments_base_parcel_idx on public.scene_deployments (base_parcel_x, base_parcel_y);

-- Every parcel touched by a deployment (many rows per scene_deployments row).
create table if not exists public.scene_deployment_parcels (
  id             bigint generated by default as identity primary key,
  deployment_id  bigint not null references public.scene_deployments (id) on delete cascade,
  x              integer not null,
  y              integer not null,
  unique (deployment_id, x, y)
);
create index if not exists scene_deployment_parcels_xy_idx on public.scene_deployment_parcels (x, y);
create index if not exists scene_deployment_parcels_deployment_idx on public.scene_deployment_parcels (deployment_id);

-- Daily rollup, one row per UTC date that had at least one deployment.
create table if not exists public.map_daily_stats (
  date              date primary key,
  deployment_count  integer not null default 0,
  scene_count       integer not null default 0,   -- distinct base parcels touched
  parcel_count      integer not null default 0,    -- distinct parcels touched
  updated_at        timestamptz not null default now()
);
create index if not exists map_daily_stats_date_idx on public.map_daily_stats (date desc);

-- ---------- Row Level Security ----------
-- Public (anon) may READ. Nothing writes through PostgREST with the anon key —
-- only the sync-map-changes Edge Function writes, using the service-role key,
-- which bypasses RLS entirely. So there is deliberately no write policy here.

alter table public.map_sync_state          enable row level security;
alter table public.scene_deployments       enable row level security;
alter table public.scene_deployment_parcels enable row level security;
alter table public.map_daily_stats         enable row level security;

